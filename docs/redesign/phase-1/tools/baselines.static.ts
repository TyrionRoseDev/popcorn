// Baselines that need no browser: build output, code shape, test health, and the final merge.
import { execSync, spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { basename, join, relative } from "node:path";
import { brotliCompressSync, constants, gzipSync } from "node:zlib";

const need = (k: string) => {
	const v = process.env[k];
	if (!v) throw new Error(`${k} not set; run through baselines.sh`);
	return v;
};
const WORK = need("BASELINE_WORK");
const REPO = need("BASELINE_REPO");
const writeSection = (name: string, value: unknown) => writeFileSync(join(WORK, "sections", `${name}.json`), `${JSON.stringify(value, null, 1)}\n`);
const readSection = (name: string) => {
	const p = join(WORK, "sections", `${name}.json`);
	return existsSync(p) ? JSON.parse(readFileSync(p, "utf8")) : null;
};

function walk(dir: string, keep: (p: string) => boolean = () => true): string[] {
	return readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
		const p = join(dir, e.name);
		if (e.isDirectory()) return walk(p, keep);
		return keep(p) ? [p] : [];
	});
}

type Asset = { name: string; kind: "js" | "css" | "other"; bytes: number; gzip: number; brotli: number };

function assetSizes(dir: string): Asset[] {
	return walk(dir).map((p) => {
		const buf = readFileSync(p);
		const kind = p.endsWith(".js") ? "js" : p.endsWith(".css") ? "css" : "other";
		return {
			name: basename(p),
			kind,
			bytes: buf.length,
			gzip: gzipSync(buf, { level: 9 }).length,
			brotli: brotliCompressSync(buf, { params: { [constants.BROTLI_PARAM_QUALITY]: 11 } }).length,
		};
	});
}

const sum = (xs: Asset[], k: "bytes" | "gzip" | "brotli") => xs.reduce((a, x) => a + x[k], 0);

async function buildSection(copy: string) {
	const assetsDir = join(copy, ".output/public/assets");
	const assets = assetSizes(assetsDir);
	const byName = new Map(assets.map((a) => [a.name, a]));
	const js = assets.filter((a) => a.kind === "js");
	const css = assets.filter((a) => a.kind === "css");

	const manifestFile = readdirSync(join(copy, ".output/server")).find((f) => f.startsWith("_tanstack-start-manifest"));
	if (!manifestFile) throw new Error("no TanStack Start manifest in .output/server");
	const { tsrStartManifest } = await import(join(copy, ".output/server", manifestFile));
	const manifest = tsrStartManifest();
	const parents = new Map<string, string>();
	for (const [id, r] of Object.entries<any>(manifest.routes)) for (const c of r.children ?? []) parents.set(c, id);
	const chain = (id: string) => {
		const out = [id];
		while (parents.has(out[0])) out.unshift(parents.get(out[0]) as string);
		return out;
	};
	const perRoute = Object.keys(manifest.routes)
		.filter((id) => !/(__root|\/route)\.tsx$/.test(manifest.routes[id].filePath ?? "__root.tsx"))
		.map((id) => {
			const names = [...new Set(chain(id).flatMap((r) => manifest.routes[r].preloads ?? []))].map((p: any) => basename(p));
			const files = names.map((n) => byName.get(n)).filter(Boolean) as Asset[];
			return {
				route: id,
				jsFiles: files.length,
				jsBytes: sum(files, "bytes"),
				jsGzip: sum(files, "gzip"),
				largest: [...files].sort((a, b) => b.bytes - a.bytes)[0]?.name,
			};
		})
		.sort((a, b) => b.jsBytes - a.jsBytes);

	const fingerprints: Record<string, RegExp> = {
		"react-devtools string": /react-devtools/i,
		"TanStack devtools string": /tanstack-devtools|TanStackDevtools|__TANSTACK_DEVTOOLS/,
		"router devtools string": /TanStackRouterDevtools|router-devtools/,
		"query devtools string": /ReactQueryDevtools|query-devtools/,
		"recharts string": /recharts/i,
	};
	const scan = Object.fromEntries(
		Object.entries(fingerprints).map(([label, re]) => [
			label,
			{
				js: js.filter((a) => re.test(readFileSync(join(assetsDir, a.name), "utf8"))).map((a) => a.name),
				css: css.filter((a) => re.test(readFileSync(join(assetsDir, a.name), "utf8"))).map((a) => a.name),
			},
		]),
	);

	const serverFiles = walk(join(copy, ".output/server"));
	const value = {
		clientJs: { files: js.length, bytes: sum(js, "bytes"), gzip: sum(js, "gzip"), brotli: sum(js, "brotli") },
		clientCss: { files: css.length, bytes: sum(css, "bytes"), gzip: sum(css, "gzip"), brotli: sum(css, "brotli") },
		largest: [...js, ...css].sort((a, b) => b.bytes - a.bytes).slice(0, 15),
		perRoute,
		scan,
		serverBytes: serverFiles.reduce((a, f) => a + statSync(f).size, 0),
		assets,
	};
	writeSection("build", value);
	return value;
}

const packageOf = (source: string) => {
	const m = source.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/g);
	if (m) return (m.at(-1) as string).replace("node_modules/", "");
	const s = source.match(/(?:^|\/)src\/([^/]+)/);
	return s ? `src/${s[1]}` : "(generated)";
};

// Attributes generated bytes to source packages from a separate sourcemapped build of the same tree.
function attributionSection(copy: string, mapCopy: string) {
	const req = createRequire(join(copy, "package.json"));
	const { TraceMap, eachMapping } = req("@jridgewell/trace-mapping");
	const dir = join(mapCopy, ".output/public/assets");
	const total: Record<string, number> = {};
	const chunks: Record<string, Record<string, number>> = {};
	for (const f of readdirSync(dir).filter((n) => n.endsWith(".js"))) {
		const mapPath = join(dir, `${f}.map`);
		if (!existsSync(mapPath)) continue;
		const lines = readFileSync(join(dir, f), "utf8").split("\n");
		const map = new TraceMap(readFileSync(mapPath, "utf8"));
		const points: { line: number; col: number; source: string }[] = [];
		eachMapping(map, (m: any) => {
			if (m.source) points.push({ line: m.generatedLine, col: m.generatedColumn, source: m.source });
		});
		points.sort((a, b) => a.line - b.line || a.col - b.col);
		const perChunk: Record<string, number> = {};
		for (const [i, p] of points.entries()) {
			const next = points[i + 1];
			const end = next && next.line === p.line ? next.col : (lines[p.line - 1]?.length ?? p.col);
			const pkg = packageOf(p.source);
			perChunk[pkg] = (perChunk[pkg] ?? 0) + (end - p.col);
		}
		for (const [k, v] of Object.entries(perChunk)) total[k] = (total[k] ?? 0) + v;
		chunks[f.replace(/-[^-]+\.js$/, "")] = perChunk;
	}
	const top = (o: Record<string, number>, n: number) =>
		Object.entries(o)
			.sort((a, b) => b[1] - a[1])
			.slice(0, n)
			.map(([pkg, bytes]) => ({ pkg, bytes }));
	const devPattern = /devtools|recharts/i;
	const value = {
		method: "sourcemap byte attribution of minified output, approximate to a few percent; separate build with vite build --sourcemap",
		packages: top(total, 25),
		devAndChartPackages: Object.entries(total).filter(([k]) => devPattern.test(k)).map(([pkg, bytes]) => ({ pkg, bytes })),
		chunks: Object.fromEntries(["main", "settings", "review-modal"].map((c) => [c, chunks[c] ? top(chunks[c], 8) : null])),
	};
	writeSection("bundle-attribution", value);
}

function run(cmd: string, cwd: string) {
	const started = Date.now();
	const r = spawnSync("sh", ["-c", cmd], { cwd, encoding: "utf8", maxBuffer: 1 << 28, env: { ...process.env, CI: "1" } });
	return { exit: r.status, out: `${r.stdout}\n${r.stderr}`, ms: Date.now() - started };
}

function countAny(src: string, copy: string) {
	const req = createRequire(join(copy, "package.json"));
	const ts = req("typescript");
	const files = walk(src, (p) => /\.tsx?$/.test(p) && !p.endsWith("routeTree.gen.ts"));
	const counts = { product: 0, tests: 0 };
	const perFile: Record<string, number> = {};
	for (const f of files) {
		const sf = ts.createSourceFile(f, readFileSync(f, "utf8"), ts.ScriptTarget.Latest, false, f.endsWith("x") ? ts.ScriptKind.TSX : ts.ScriptKind.TS);
		let n = 0;
		const visit = (node: any) => {
			if (node.kind === ts.SyntaxKind.AnyKeyword) n++;
			ts.forEachChild(node, visit);
		};
		visit(sf);
		const bucket = /__tests__|\.test\./.test(f) ? "tests" : "product";
		counts[bucket] += n;
		if (n) perFile[relative(src, f)] = n;
	}
	return { ...counts, top: Object.entries(perFile).sort((a, b) => b[1] - a[1]).slice(0, 8) };
}

function procedures(copy: string) {
	const probe = join(WORK, "count-procedures.ts");
	writeFileSync(probe, `import { trpcRouter } from "${join(copy, "src/integrations/trpc/router.ts")}";\nconst keys = Object.keys(trpcRouter._def.procedures);\nconst by = {};\nfor (const k of keys) { const r = k.split(".")[0]; by[r] = (by[r] ?? 0) + 1; }\nconsole.log(JSON.stringify({ total: keys.length, byRouter: by }));\n`);
	const dummy = "DATABASE_URL=postgresql://none:none@127.0.0.1:1/none BETTER_AUTH_URL=http://localhost:1 BETTER_AUTH_SECRET=x RESEND_API_KEY=x RESEND_FROM_EMAIL=a@b.co UPLOADTHING_TOKEN=x TMDB_READ_ACCESS_TOKEN=x CRON_SECRET=x";
	const r = run(`${dummy} bun --no-env-file ${probe}`, copy);
	const line = r.out.split("\n").find((l) => l.startsWith("{"));
	return line ? JSON.parse(line) : { error: r.out.slice(0, 400) };
}

function codeSection(copy: string) {
	const src = join(copy, "src");
	const isCode = (p: string) => /\.(ts|tsx)$/.test(p) && !p.endsWith("routeTree.gen.ts");
	const rows = walk(src, isCode).map((p) => {
		const text = readFileSync(p, "utf8");
		return { file: relative(copy, p), lines: text.split("\n").length - 1, code: text.split("\n").filter((l) => l.trim()).length };
	});
	const product = rows.filter((r) => !/__tests__|\.test\./.test(r.file));
	const top = (prefix: string) => product.filter((r) => r.file.startsWith(prefix)).sort((a, b) => b.lines - a.lines).slice(0, 20);
	const schema = readFileSync(join(src, "db/schema.ts"), "utf8");
	const allText = walk(src, isCode).map((p) => readFileSync(p, "utf8"));
	const tally = (re: RegExp) => allText.reduce((a, t) => a + (t.match(re)?.length ?? 0), 0);

	const tsc = run("bun run typecheck", copy);
	const tscErrors = tsc.out.split("\n").filter((l) => /error TS\d+/.test(l));
	const biome = run("bunx biome ci . --reporter=github --max-diagnostics=none", copy);
	const biomeLines = biome.out.split("\n").filter((l) => /^::(error|warning|notice)/.test(l));
	const biomeRules: Record<string, number> = {};
	for (const l of biomeLines) {
		const m = l.match(/title=([^,:]+)/);
		const k = `${l.slice(2, 7).replace(/ .*/, "")} ${m?.[1] ?? "unknown"}`;
		biomeRules[k] = (biomeRules[k] ?? 0) + 1;
	}
	writeSection("code", {
		srcFiles: rows.length,
		srcLines: rows.reduce((a, r) => a + r.lines, 0),
		productLines: product.reduce((a, r) => a + r.lines, 0),
		routesTop20: top("src/routes/"),
		componentsTop20: top("src/components/"),
		over500: product.filter((r) => r.lines > 500).sort((a, b) => b.lines - a.lines),
		trpcProcedures: procedures(copy),
		tables: schema.match(/pgTable\(/g)?.length ?? 0,
		todoFixme: tally(/\b(TODO|FIXME|HACK|XXX)\b/g),
		biomeIgnores: tally(/biome-ignore/g),
		tsIgnores: tally(/@ts-(ignore|expect-error|nocheck)/g),
		any: countAny(src, copy),
		tsc: { exit: tsc.exit, errors: tscErrors.length, sample: tscErrors.slice(0, 10) },
		biome: { exit: biome.exit, diagnostics: biomeLines.length, byRule: biomeRules, tail: biome.out.trim().split("\n").slice(-4) },
	});
}

function testsSection(copy: string) {
	const RUNS = Number(process.env.BASELINE_TEST_RUNS ?? 3);
	const runs = [];
	for (let i = 0; i < RUNS; i++) {
		const out = join(WORK, `vitest-${i}.json`);
		const r = run(`bun run test --reporter=json --outputFile=${out}`, copy);
		const j = existsSync(out) ? JSON.parse(readFileSync(out, "utf8")) : null;
		const failures = (j?.testResults ?? []).flatMap((f: any) =>
			f.assertionResults
				.filter((a: any) => a.status === "failed")
				.map((a: any) => ({ file: relative(copy, f.name), test: a.fullName, message: a.failureMessages?.[0]?.split("\n")[0]?.slice(0, 200) })),
		);
		const brokenFiles = (j?.testResults ?? [])
			.filter((f: any) => f.status === "failed" && !f.assertionResults.length)
			.map((f: any) => ({ file: relative(copy, f.name), message: f.message?.split("\n")[0]?.slice(0, 200) }));
		runs.push({ exit: r.exit, total: j?.numTotalTests, passed: j?.numPassedTests, failed: j?.numFailedTests, skipped: j?.numPendingTests, suites: j?.numTotalTestSuites, files: j?.testResults?.length, failures, brokenFiles });
	}
	const routersDir = join(copy, "src/integrations/trpc/routers");
	const routers = readdirSync(routersDir).map((f) => f.replace(/\.ts$/, "")).sort();
	const testFiles = walk(join(copy, "src"), (p) => /\.test\.tsx?$/.test(p));
	const texts = testFiles.map((p) => ({ file: relative(copy, p), text: readFileSync(p, "utf8") }));
	const coverage = routers.map((r) => ({ router: r, tests: texts.filter((t) => new RegExp(`(from|import\\()\\s*["'][^"']*routers/${r}["']`).test(t.text)).map((t) => t.file) }));
	const ci = readFileSync(join(copy, ".github/workflows/ci.yml"), "utf8");
	const pkg = JSON.parse(readFileSync(join(copy, "package.json"), "utf8"));
	const allDeps = { ...pkg.dependencies, ...pkg.devDependencies };
	writeSection("tests", {
		command: "bun run test (vitest run --passWithNoTests)",
		runs,
		testFiles: testFiles.map((p) => relative(copy, p)),
		routers: coverage,
		routersWithoutTest: coverage.filter((c) => !c.tests.length).map((c) => c.router),
		ci: {
			triggers: ci.match(/^on:\n((?:\s+.*\n)+?)\n/m)?.[1]?.trim(),
			steps: [...ci.matchAll(/- name: (.+)/g)].map((m) => m[1]),
			e2eInCi: /playwright|cypress|e2e|webdriver|puppeteer/i.test(ci),
			e2eDeps: Object.keys(allDeps).filter((d) => /playwright|cypress|webdriver|puppeteer/.test(d)),
			coverageConfigured: /coverage/.test(ci) || !!allDeps["@vitest/coverage-v8"],
		},
	});
}

function serverLogCensus() {
	const log = join(WORK, "prod.log");
	if (!existsSync(log)) return null;
	const counts: Record<string, number> = {};
	for (const line of readFileSync(log, "utf8").split("\n")) {
		const m = line.match(/^(\w*Error: .{0,100})|\b(WARN|ERROR) \[[^\]]+\]: (.{0,80})/);
		if (m) {
			const k = (m[1] ?? `${m[2]} ${m[3]}`).trim();
			counts[k] = (counts[k] ?? 0) + 1;
		}
	}
	return Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([message, count]) => ({ message, count }));
}

function loadNow() {
	const m = execSync("uptime", { encoding: "utf8" }).match(/load averages?:\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)/);
	return { load1: Number(m?.[1]), load5: Number(m?.[2]), load15: Number(m?.[3]), ncpu: Number(execSync("sysctl -n hw.ncpu", { encoding: "utf8" }).trim()) };
}

// A timing-only re-run has fresh sections for timing alone, so everything else is kept from the previous JSON.
function merge() {
	const out = need("BASELINE_OUT");
	const prev = existsSync(out) ? JSON.parse(readFileSync(out, "utf8")) : {};
	const git = (c: string) => execSync(`git ${c}`, { cwd: REPO, encoding: "utf8" }).trim();
	const build = readSection("build") ?? prev.build;
	const runtime = readSection("runtime") ?? prev.runtime;
	const lhPerf = readSection("lighthouse-perf") ?? prev.lighthouse?.perf;
	if (build && runtime) {
		const byName = new Map(build.assets.map((a: Asset) => [a.name, a]));
		for (const r of runtime.routes) {
			const files = r.scripts.map((n: string) => byName.get(n)).filter(Boolean) as Asset[];
			r.jsLoaded = { files: files.length, bytes: sum(files, "bytes"), gzip: sum(files, "gzip") };
		}
	}
	const { samples: runtimeSamples = [], ...runtimeSummary } = runtime ?? {};
	const { samples: perfSamples = [], ...perfSummary } = lhPerf ?? {};
	const flatten = ({ load, ...rest }: any) => (load ? { ...rest, ...load } : rest);
	const freshRuntime = !!readSection("runtime");
	const freshPerf = !!readSection("lighthouse-perf");
	const keptSamples = (prev.timingSamples ?? []).filter((s: any) => (s.metric === "lighthouse-perf" ? !freshPerf : !freshRuntime));
	const timingSamples = [...keptSamples, ...[...runtimeSamples, ...perfSamples].map(flatten)];
	const value = {
		meta: {
			generatedAt: new Date().toISOString(),
			head: git("rev-parse --short HEAD"),
			dirtyFiles: git("status --short").split("\n").filter(Boolean).length,
			note: "Tree under test is HEAD plus uncommitted changes, built in a copy and served by bun .output/server/index.mjs on localhost.",
			machine: `${execSync("sysctl -n machdep.cpu.brand_string", { encoding: "utf8" }).trim()}, ${execSync("sysctl -n hw.ncpu", { encoding: "utf8" }).trim()} logical cores`,
			bun: execSync("bun -v", { encoding: "utf8" }).trim(),
			loadAtMerge: loadNow(),
			timingPolicy: "A timing sample is PROVISIONAL when the 1-minute load exceeds ncpu before or after it. Aggregates fill `baseline` from clean samples only, and need at least 3. Exclude rows of timingSamples whose status is PROVISIONAL from any before/after comparison.",
			timingSampleCounts: {
				baseline: timingSamples.filter((s: any) => s.status === "BASELINE").length,
				provisional: timingSamples.filter((s: any) => s.status === "PROVISIONAL").length,
			},
		},
		seed: readSection("seed") ?? prev.seed,
		build,
		bundleAttribution: readSection("bundle-attribution") ?? prev.bundleAttribution,
		code: readSection("code") ?? prev.code,
		tests: readSection("tests") ?? prev.tests,
		axe: readSection("axe") ?? prev.axe,
		lighthouse: { quality: stripSamples(readSection("lighthouse-quality")) ?? prev.lighthouse?.quality, perf: lhPerf ? perfSummary : null },
		runtime: runtime ? runtimeSummary : null,
		timingSamples,
		serverLogErrors: serverLogCensus() ?? prev.serverLogErrors,
		keyboard: readSection("keyboard") ?? prev.keyboard,
		motionZoom: readSection("motion-zoom") ?? prev.motionZoom,
	};
	mkdirSync(join(out, ".."), { recursive: true });
	writeFileSync(out, `${JSON.stringify(value, null, 1)}\n`);
	console.log(`wrote ${out}; timing samples ${JSON.stringify(value.meta.timingSampleCounts)}`);
}

function stripSamples(section: any) {
	if (!section) return null;
	const { samples, ...rest } = section;
	return { ...rest, loadPerRun: samples.map((s: any) => ({ id: s.id, preset: s.preset, run: s.run, ...s.load })) };
}

const kb = (n: number) => `${(n / 1024).toFixed(0)} KB`;
const spread = (s: any, d = 0) => (s?.median == null ? "n/a" : s.min === s.max ? `${s.median.toFixed(d)}` : `${s.median.toFixed(d)} (${s.min.toFixed(d)} to ${s.max.toFixed(d)})`);
const timed = (s: any, d = 0) => (s?.status === "BASELINE" ? spread(s.baseline, d) : "pending");
const row = (cells: unknown[]) => `| ${cells.join(" | ")} |`;
const table = (head: string[], rows: unknown[][]) => [row(head), row(head.map(() => "---")), ...rows.map(row)].join("\n");

// Prints the markdown tables used in 06-baselines.md from 06-baselines.json.
function tables() {
	const j = JSON.parse(readFileSync(need("BASELINE_OUT"), "utf8"));
	const out: string[] = [];
	const quality = j.lighthouse.quality?.summary ?? [];
	const perfRows = j.lighthouse.perf?.summary ?? [];
	out.push("### Lighthouse quality");
	out.push(table(["Route", "Preset", "Valid runs", "Accessibility", "SEO", "Best Practices"], quality.map((r: any) => [r.id, r.preset, `${r.validRuns}/${r.runs}`, spread(r.scores.accessibility), spread(r.scores.seo), spread(r.scores["best-practices"])])));
	for (const variant of ["as-served", "gzip", "no-tmdb-images"]) {
		out.push(`### Lighthouse performance ${variant}`);
		out.push(table(["Route", "Preset", "Clean/total runs", "Performance", "LCP ms", "FCP ms", "TBT ms", "CLS"], perfRows.filter((r: any) => r.variant === variant).map((r: any) => [r.id, r.preset, `${r.scores.performance.cleanSamples}/${r.runs}`, timed(r.scores.performance), timed(r.metrics.lcpMs), timed(r.metrics.fcpMs), timed(r.metrics.tbtMs), timed(r.metrics.cls, 3)])));
	}
	const census = new Map<string, any>();
	for (const r of quality) {
		for (const c of ["accessibility", "seo", "best-practices"]) {
			for (const a of r.failing[c]) {
				const k = `${c}|${a.id}`;
				const e = census.get(k) ?? { c, id: a.id, title: a.title, weight: a.weight, cells: [] };
				e.cells.push(`${r.id}/${r.preset}`);
				census.set(k, e);
			}
		}
	}
	out.push("### Lighthouse failing audits");
	out.push(table(["Category", "Audit", "Weight", "Cells failing", "Where"], [...census.values()].sort((a, b) => a.c.localeCompare(b.c) || b.cells.length - a.cells.length).map((e) => [e.c, e.id, e.weight, e.cells.length, [...new Set(e.cells.map((c: string) => c.split("/")[0]))].join(", ")])));

	const a = j.axe;
	out.push("### axe totals, node counts summed over scenarios");
	const impacts = ["critical", "serious", "moderate", "minor"];
	out.push(table(["Scope", ...impacts], ["routes", "modals"].map((s) => [s, ...impacts.map((i) => spread(a.totals[s].byImpact[i]))])));
	out.push("### axe totals by tag bucket, routes");
	out.push(table(["Tag", ...impacts], a.tags.map((t: string) => [t, ...impacts.map((i) => spread(a.totals.routes.byBucket[t][i]))])));
	out.push("### axe totals by tag bucket, modals");
	out.push(table(["Tag", ...impacts], a.tags.map((t: string) => [t, ...impacts.map((i) => spread(a.totals.modals.byBucket[t][i]))])));
	out.push("### axe rules, pass 0");
	out.push(table(["Rule", "Impact", "Nodes", "Scenarios", "Distinct selectors", "Example"], a.rules.map((r: any) => [r.id, r.impact, r.nodes, r.scenarios, r.distinct, `\`${String(r.example?.target ?? "").slice(0, 60).replaceAll("|", "/")}\``])));
	out.push("### axe needs-review (incomplete), pass 0");
	out.push(table(["Rule", "Nodes", "Scenarios", "Reasons"], a.incomplete.map((r: any) => [r.id, r.nodes, r.scenarios, Object.entries(r.reasons).sort((x: any, y: any) => y[1] - x[1]).slice(0, 4).map(([k, v]) => `${k} ${v}`).join(", ")])));
	out.push("### axe per screen, medians, critical/serious/moderate");
	const screens = new Map<string, any>();
	for (const s of a.perScenario) {
		const e = screens.get(s.route) ?? {};
		if (!s.skipped) e[`${s.state}|${s.viewport}`] = `${s.impacts.critical.median}/${s.impacts.serious.median}/${s.impacts.moderate.median}`;
		screens.set(s.route, e);
	}
	const cols = ["signed-out|mobile", "signed-out|desktop", "newbie|mobile", "newbie|desktop", "empty|mobile", "empty|desktop", "populated|mobile", "populated|desktop", "modal|mobile", "modal|desktop"];
	const used = cols.filter((c) => [...screens.values()].some((e) => e[c]));
	out.push(table(["Screen", ...used.map((c) => c.replace("|", " "))], [...screens.entries()].map(([k, e]) => [k, ...used.map((c) => e[c] ?? "")])));
	out.push("### unnamed controls per route, pass 0, axe rule counts");
	out.push(table(["Scenario", "Counts"], Object.entries<any>(a.unnamed).map(([k, v]) => [k.replaceAll("|", " "), Object.entries(v).map(([r, n]) => `${r} ${n}`).join(", ")])));

	const b = j.build;
	out.push("### build largest");
	out.push(table(["File", "Raw", "Gzip", "Brotli"], b.largest.slice(0, 10).map((x: any) => [x.name, kb(x.bytes), kb(x.gzip), kb(x.brotli)])));
	out.push("### build per route");
	out.push(table(["Route", "JS files", "JS raw", "JS gzip"], b.perRoute.map((r: any) => [r.route, r.jsFiles, kb(r.jsBytes), kb(r.jsGzip)])));
	out.push("### runtime");
	out.push(table(["Route", "Requests", "Own", "External", "tRPC HTTP", "Procedure calls", "JS loaded gzip", "Failed", "Slowest tRPC ms"], j.runtime.routes.map((r: any) => [r.id, spread(r.requests), spread(r.ownRequests), spread(r.externalRequests), spread(r.trpcHttp), spread(r.procedureCalls), kb(r.jsLoaded?.gzip ?? 0), r.failed.length, timed(r.trpcSlowestMs)])));
	out.push("### server");
	out.push(table(["Route", "Status", "HTML bytes", "TTFB ms", "Total ms"], Object.entries<any>(j.runtime.server).map(([k, v]) => [k, v.statuses.join(","), spread(v.htmlBytes), timed(v.ttfbMs, 1), timed(v.totalMs, 1)])));
	out.push(`Title cold TTFB ms: ${timed(j.runtime.titleCold.ttfbMs, 1)}. TMDB direct ms: ${timed(j.runtime.tmdbDirectMs, 1)}.`);
	out.push(`Timing samples: ${JSON.stringify(j.meta.timingSampleCounts)}`);
	console.log(out.join("\n\n"));
}

